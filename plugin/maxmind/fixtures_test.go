// localizedNames returns the names of a place in the given languages. Each
// name mentions its language, so that names can't be mixed up unnoticed.
func localizedNames(place string, languages []string) mmdbtype.Map {
	names := make(mmdbtype.Map, len(languages))
	for _, language := range languages {
		names[mmdbtype.String(language)] = mmdbtype.String(place + " (" + language + ")")
	}
	return names
}

// blankNames returns the names of a place that has none in the given languages.
func blankNames(languages []string) mmdbtype.Map {
	names := make(mmdbtype.Map, len(languages))
	for _, language := range languages {
		names[mmdbtype.String(language)] = mmdbtype.String("")
	}
	return names
}

// continentData returns a continent as stored in GeoLite2 and DB-IP country
// databases, where nil names stand for a continent without localized names.
func continentData(code string, geoNameID uint32, names mmdbtype.Map) mmdbtype.Map {
	data := mmdbtype.Map{
		"code":       mmdbtype.String(code),
		"geoname_id": mmdbtype.Uint32(geoNameID),
	}
	if names != nil {
		data["names"] = names
	}
	return data
}

// countryData returns a country as stored in GeoLite2 and DB-IP country
// databases, where nil names stand for a country without localized names.
func countryData(isoCode string, geoNameID uint32, inEU bool, names mmdbtype.Map) mmdbtype.Map {
	data := mmdbtype.Map{
		"iso_code":             mmdbtype.String(isoCode),
		"geoname_id":           mmdbtype.Uint32(geoNameID),
		"is_in_european_union": mmdbtype.Bool(inEU),
	}
	if names != nil {
		data["names"] = names
	}
	return data
}

// representedCountryData returns a country in the form of a represented
// country, which additionally tells the type of what represents the country.
func representedCountryData(country mmdbtype.Map) mmdbtype.Map {
	data := maps.Clone(country)
	data["type"] = mmdbtype.String("military")
	return data
}

// countryMMDBRecords returns the records of a database in the format shared
// by GeoLite2 and DB-IP country databases, whose names are localized in the
// given languages.
func countryMMDBRecords(languages []string) []mmdbRecord {
	asia := continentData("AS", 6255147, localizedNames("Asia", languages))
	europe := continentData("EU", 6255148, localizedNames("Europe", languages))
	northAmerica := continentData("NA", 6255149, localizedNames("North America", languages))

	china := countryData("CN", 1814991, false, localizedNames("China", languages))
	germany := countryData("DE", 2921044, true, localizedNames("Germany", languages))
	usa := countryData("US", 6252001, false, localizedNames("United States", languages))

	return []mmdbRecord{
		{"1.0.1.0/24", mmdbtype.Map{"continent": asia, "country": china, "registered_country": china}},
		// The country takes precedence over the registered country.
		{"1.0.2.0/23", mmdbtype.Map{"continent": asia, "country": china, "registered_country": usa}},
		// The registered country takes precedence over the represented country.
		{"5.1.0.0/16", mmdbtype.Map{"continent": europe, "registered_country": germany, "represented_country": representedCountryData(usa)}},
		// The represented country is the last resort.
		{"6.0.0.0/8", mmdbtype.Map{"represented_country": representedCountryData(usa)}},
		// A network without any country belongs to no list.
		{"7.0.0.0/8", mmdbtype.Map{"continent": europe}},
		{"8.8.8.0/24", mmdbtype.Map{"continent": northAmerica, "country": usa, "registered_country": usa}},
		{"2001:250::/35", mmdbtype.Map{"continent": asia, "country": china}},
		// ISO codes are trimmed and upper-cased.
		{"2001:4860::/32", mmdbtype.Map{"country": mmdbtype.Map{"iso_code": mmdbtype.String(" us ")}}},
	}
}

// ipinfoPlace returns the location fields of a record of an IPInfo Lite database.
func ipinfoPlace(continentCode, continent, countryCode, country string) mmdbtype.Map {
	return mmdbtype.Map{
		"continent_code": mmdbtype.String(continentCode),
		"continent":      mmdbtype.String(continent),
		"country_code":   mmdbtype.String(countryCode),
		"country":        mmdbtype.String(country),
	}
}

// ipinfoData returns a record of an IPInfo Lite database, which tells the
// place and the AS of a network.
func ipinfoData(place mmdbtype.Map, asn string) mmdbtype.Map {
	data := maps.Clone(place)
	data["asn"] = mmdbtype.String(asn)
	data["as_name"] = mmdbtype.String("Name of " + asn)
	data["as_domain"] = mmdbtype.String(strings.ToLower(asn) + ".example")
	return data
}

// ipinfoMMDBRecords returns the records of a database in the format of
// IPInfo Lite databases.
func ipinfoMMDBRecords() []mmdbRecord {
	china := ipinfoPlace("AS", "Asia", "CN", "China")
	germany := ipinfoPlace("EU", "Europe", "DE", "Germany")
	usa := ipinfoPlace("NA", "North America", "US", "United States")

	return []mmdbRecord{
		{"1.0.1.0/24", ipinfoData(china, "AS4134")},
		{"1.0.2.0/23", ipinfoData(china, "AS4837")},
		{"5.1.0.0/16", ipinfoData(germany, "AS3320")},
		{"6.0.0.0/8", ipinfoData(usa, "AS668")},
		{"8.8.8.0/24", ipinfoData(usa, "AS15169")},
		{"2001:250::/35", ipinfoData(china, "AS4538")},
		// Country codes are trimmed and upper-cased.
		{"2001:4860::/32", ipinfoData(ipinfoPlace("NA", "North America", " us ", "United States"), "AS15169")},
	}
}
